// Teste de navegador (Playwright/Chromium headless) contra o app PUBLICADO no GitHub Pages, com a senha real (lida do arquivo local).
//   node tests/e2e-ui.mjs [URL]
import { chromium, devices } from 'playwright'
import { mkdirSync, readFileSync, existsSync } from 'node:fs'
import { PASSWORD, check, section, summary } from './lib.mjs'

const URL = process.argv[2] ?? 'https://drthaleschateaubriand.github.io/anotacao-medica/'
const DIR = process.env.SHOTS_DIR ?? '/workspace/anotacao-medica-private/screens'
mkdirSync(DIR, { recursive: true })
const browser = await chromium.launch()
const marker = 'NOTA-UI-' + Date.now()
const errors = []

async function newPage(opts) {
  const ctx = await browser.newContext({ locale: 'pt-BR', permissions: ['clipboard-read', 'clipboard-write'], acceptDownloads: true, ...opts })
  const page = await ctx.newPage()
  page.on('pageerror', (e) => errors.push(String(e)))
  page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()) })
  return { ctx, page }
}
const noHScroll = (p) => p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
async function doLogin(page, pw) {
  await page.fill('[data-testid="password-input"]', pw)
  await page.click('[data-testid="login-submit"]')
}

section('Carregamento (iPhone 390x844)')
const { ctx, page } = await newPage({ ...devices['iPhone 13'], viewport: { width: 390, height: 844 } })
const resp = await page.goto(URL, { waitUntil: 'networkidle' })
check('página carrega (HTTP 200)', resp.status() === 200)
check('título "Anotação Médica"', (await page.title()) === 'Anotação Médica')
await page.screenshot({ path: `${DIR}/01-login-mobile.png` })
check('sem rolagem horizontal', await noHScroll(page))
check('tela de login pede SENHA (campo password) e não há "criar conta"/"gerar"/QR', (await page.locator('[data-testid="password-input"]').getAttribute('type')) === 'password' && (await page.locator('text=/criar conta|gerar (código|senha)|qr code/i').count()) === 0)
const fs = await page.$eval('[data-testid="password-input"]', (e) => parseFloat(getComputedStyle(e).fontSize))
check(`campo com fonte >= 16px (${fs}px; sem zoom no iOS)`, fs >= 16)
const sw = await page.evaluate(async () => { await navigator.serviceWorker.ready; return (await navigator.serviceWorker.getRegistration())?.scope })
check(`service worker com escopo do subcaminho (${sw})`, sw === URL)
const man = await page.evaluate(async () => { const l = document.querySelector('link[rel="manifest"]').href; const r = await fetch(l); const j = await r.json(); return { ok: r.ok, name: j.name, icons: j.icons.length, scope: j.scope } })
check(`manifest PWA ok (${man.name})`, man.ok && man.name === 'Anotação Médica' && man.icons >= 4)

