check('senha errada mostra erro', /incorreta/i.test(await page.textContent('[data-testid="login-error"]')))
await page.fill('[data-testid="password-input"]', '')
await doLogin(page, PASSWORD)
await page.waitForSelector('[data-testid="topnav"]', { timeout: 20000 })
check('senha certa entra e abre direto em Notas', (await page.getAttribute('[data-testid="tab-notes"]', 'aria-current')) === 'page' && (await page.getAttribute('[data-testid="tab-chat"]', 'aria-current')) === null)
check('duas áreas na navegação: Notas e Chat IA', (await page.locator('[data-testid="tab-notes"]').count()) === 1 && (await page.locator('[data-testid="tab-chat"]').count()) === 1)
