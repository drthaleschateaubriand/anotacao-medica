// Ponta a ponta contra o backend PUBLICADO (Supabase Edge Functions am-*) com a SENHA REAL (lida do arquivo local, nunca impressa).
//   node tests/e2e.mjs
import { ADMIN, ORIGIN, PASSWORD, admin, call, chat, check, login, section, sleep, summary } from './lib.mjs'

if (!PASSWORD) throw new Error('senha não encontrada (arquivo local)')
const created = { notes: [], skills: [], agents: [], convs: [], mems: [] }

section('Acesso: cadastro fechado, senha errada, senha certa, CORS')
for (const a of ['register', 'signup', 'recover', 'reset', 'generate-code', 'challenge', 'pow-challenge']) {
  const r = await call('auth', a, {})
  check(`auth/${a} responde 403`, r.status === 403, String(r.status))
}
const wrong = await login('senha-errada-xyz')
check('senha errada => 401 "Senha incorreta."', wrong.status === 401 && /Senha incorreta/.test(wrong.json.message), JSON.stringify(wrong.json))
const nopw = await call('auth', 'login', {})
check('login sem senha => 401', nopw.status === 401)
const lower = await login(PASSWORD.toLowerCase())
check('mesma senha em minúsculas => 401 (sensível a maiúsculas)', lower.status === 401)
const evil = await call('auth', 'login', { password: PASSWORD }, undefined, { Origin: 'https://evil.example' })
check('origem não permitida => 403', evil.status === 403)
const okTrim = await login('  ' + PASSWORD + '  ')
check('senha certa com espaços nas pontas => 200 (trim)', okTrim.status === 200 && !!okTrim.json.access_token)
const s1 = await login(PASSWORD, { device_name: 'teste-1' })
check('senha certa => sessão (access + refresh)', s1.status === 200 && s1.json.access_token && s1.json.refresh_token)
check('resposta do login não contém a senha', !JSON.stringify(s1.json).includes(PASSWORD))
const T = s1.json.access_token
check('sem token => 401 em am-data', (await call('data', 'bootstrap', {})).status === 401)
const me = await call('auth', 'me', {}, T)
check('auth/me', me.status === 200 && me.json.user?.id)

section('Refresh com rotação')
const rf = await call('auth', 'refresh', { refresh_token: s1.json.refresh_token })
check('refresh devolve novos tokens', rf.status === 200 && rf.json.access_token && rf.json.refresh_token !== s1.json.refresh_token)
await sleep(21_000)
const reuse = await call('auth', 'refresh', { refresh_token: s1.json.refresh_token })
check('reuso do refresh antigo => 401', reuse.status === 401, String(reuse.status))
const afterReuse = await call('data', 'bootstrap', {}, rf.json.access_token)
check('reuso revoga a sessão (token novo também cai)', afterReuse.status === 401, String(afterReuse.status))

const s2 = await login(PASSWORD, { device_name: 'teste-2' })
const A = s2.json.access_token
const boot = await call('data', 'bootstrap', {}, A)
check('bootstrap (preferências, notas, skills, agentes)', boot.status === 200 && boot.json.preferences && Array.isArray(boot.json.notes) && Array.isArray(boot.json.skills) && Array.isArray(boot.json.agents))

section('NOTAS: criar, editar (autosave), pesquisar, fixar, persistir após novo login, exportar, excluir')
const marker = 'ZQXMARCA' + Date.now()
const n1 = await call('data', 'note.create', { title: 'Plantão ' + marker, content: 'Primeira linha\n  segunda com espaços\n' + marker }, A)
check('criar nota (201)', n1.status === 201 && n1.json.note.id)
const id1 = n1.json.note.id; created.notes.push(id1)
const n2 = await call('data', 'note.create', { title: 'Outra nota', content: 'texto sem marcador' }, A); created.notes.push(n2.json.note.id)
const up = await call('data', 'note.update', { id: id1, content: 'Primeira linha editada\n  segunda com espaços\n' + marker, base_updated_at: n1.json.note.updated_at }, A)
check('editar nota (autosave) com controle de versão', up.status === 200 && /editada/.test(up.json.note.content) && up.json.note.updated_at !== n1.json.note.updated_at)
check('texto livre preserva espaços e quebras de linha', up.json.note.content.includes('\n  segunda com espaços\n'))
const conflict = await call('data', 'note.update', { id: id1, content: 'versão velha', base_updated_at: n1.json.note.updated_at }, A)
check('edição com versão velha => 409 + nota atual (sem sobrescrever)', conflict.status === 409 && conflict.json.note?.id === id1)
const ren = await call('data', 'note.update', { id: id1, title: 'Renomeada ' + marker, base_updated_at: up.json.note.updated_at }, A)
check('renomear (título) mantém o texto', ren.status === 200 && ren.json.note.title.startsWith('Renomeada') && /editada/.test(ren.json.note.content))
const found = await call('data', 'note.list', { q: marker }, A)
check('pesquisar encontra por título/texto', found.json.notes?.some((n) => n.id === id1) && !found.json.notes.some((n) => n.id === n2.json.note.id))
const none = await call('data', 'note.list', { q: 'xxnaoexistexx' + marker }, A)
check('pesquisa sem resultado => lista vazia', none.json.notes?.length === 0)
const pin = await call('data', 'note.update', { id: n2.json.note.id, pinned: true }, A)
const lst = await call('data', 'note.list', {}, A)
check('fixar: nota fixada vem primeiro', pin.json.note.pinned === true && lst.json.notes[0].id === n2.json.note.id)
check('lista traz prévia (snippet) sem o texto inteiro', lst.json.notes.every((n) => 'snippet' in n && !('content' in n)))
const special = await call('data', 'note.list', { q: '%_\\' }, A)
check('busca com curingas %_\\ não quebra', special.status === 200)
const tooBig = await call('data', 'note.update', { id: id1, content: 'x'.repeat(100_001) }, A)
check('texto acima de 100 mil caracteres => 400', tooBig.status === 400)
const s3 = await login(PASSWORD, { device_name: 'teste-3 (novo login)' })
const B = s3.json.access_token
const g = await call('data', 'note.get', { id: id1 }, B)
check('nota persiste após NOVO login', g.status === 200 && g.json.note.title.startsWith('Renomeada') && g.json.note.content.includes('editada'))
const exp = await call('data', 'export.all', {}, B)
check('exportação JSON inclui notas', exp.status === 200 && exp.json.app === 'Anotação Médica' && exp.json.notes.some((n) => n.id === id1))
check('exportação não contém hash/senha', !JSON.stringify(exp.json).includes('pbkdf2') && !JSON.stringify(exp.json).includes(PASSWORD))
const del = await call('data', 'note.delete', { id: id1 }, B)
check('excluir nota', del.status === 200)
check('nota excluída => 404 e some da lista', (await call('data', 'note.get', { id: id1 }, B)).status === 404 && !(await call('data', 'note.list', {}, B)).json.notes.some((n) => n.id === id1))
check('id inválido => 400', (await call('data', 'note.get', { id: 'x' }, B)).status === 400)

section('SKILLS + AGENTE: CRUD, anexar, global')
const sk = await call('data', 'skill.create', { name: 'Teste fecho', description: 'e2e', instructions: 'REGRA FIXA: termine TODA resposta com uma última linha contendo exatamente o código FECHO-7QX (e nada depois dele).', is_global: true }, B)
check('criar skill global', sk.status === 201 && sk.json.skill.is_global === true); created.skills.push(sk.json.skill.id)
const sk2 = await call('data', 'skill.create', { name: 'Teste abertura', instructions: 'REGRA FIXA: comece TODA resposta com a palavra exata ABERTURA-3ZK seguida de dois pontos.' }, B)
check('criar skill (não global)', sk2.status === 201 && sk2.json.skill.is_global === false); created.skills.push(sk2.json.skill.id)
const ag = await call('data', 'agent.create', { name: 'Agente teste', emoji: '🧪', instructions: 'Você é um assistente de teste. Responda em uma frase curta.' }, B)
check('criar agente', ag.status === 201); created.agents.push(ag.json.agent.id)
const setk = await call('data', 'agent.set_skills', { id: ag.json.agent.id, skill_ids: [sk2.json.skill.id] }, B)
check('anexar skill ao agente', setk.status === 200 && setk.json.agents.find((a) => a.id === ag.json.agent.id)?.skill_ids?.[0] === sk2.json.skill.id)
check('skill inexistente/alheia => 404', (await call('data', 'agent.set_skills', { id: ag.json.agent.id, skill_ids: ['00000000-0000-4000-8000-000000000000'] }, B)).status === 404)
check('skill sem instruções => 400', (await call('data', 'skill.create', { name: 'x', instructions: ' ' }, B)).status === 400)
const upS = await call('data', 'skill.update', { id: sk2.json.skill.id, name: 'Teste abertura', instructions: sk2.json.skill.instructions, is_global: false, description: 'editada' }, B)
check('editar skill', upS.status === 200 && upS.json.skill.description === 'editada')
const dup = await call('data', 'skill.duplicate', { id: sk2.json.skill.id }, B); created.skills.push(dup.json.skill?.id)
check('duplicar skill', dup.status === 201 && /cópia/.test(dup.json.skill.name))

section('CHAT real com IA gratuita: conversa, histórico, memória')
const mem = await call('data', 'mem.create', { content: 'O nome do gato do usuário é Mingau (teste e2e).' }, B); created.mems.push(mem.json.memory?.id)
check('criar memória', mem.status === 201)
const c0 = await chat(B, { content: 'Responda apenas com a palavra OK.', model: 'auto' })
check(`resposta real da IA (${c0.done?.provider}/${c0.done?.model})`, c0.status === 200 && c0.text.length > 0, JSON.stringify(c0.error ?? c0.json ?? ''))
if (c0.conversation_id) created.convs.push(c0.conversation_id)
// Obs.: há skill global ativa ("FECHO-7QX") — a primeira conversa já deve refletir
check('skill GLOBAL entrou no prompt e mudou a resposta (FECHO-7QX)', /FECHO-7QX/.test(c0.text), JSON.stringify(c0.text.slice(-120)))
const cm = await chat(B, { content: 'Qual é o nome do meu gato? Responda só o nome.', model: 'auto' })
if (cm.conversation_id) created.convs.push(cm.conversation_id)
check('MEMÓRIA entrou no prompt (resposta cita Mingau)', /Mingau/i.test(cm.text), JSON.stringify(cm.text.slice(0, 120)))
const cn = await chat(B, { conversation_id: c0.conversation_id, content: 'Agora responda com a palavra FIM.' })
check('segunda mensagem na mesma conversa', cn.status === 200 && cn.text.length > 0)
const ca = await chat(B, { content: 'Diga olá.', agent_id: ag.json.agent.id })
if (ca.conversation_id) created.convs.push(ca.conversation_id)
check('AGENTE + skill do agente: resposta começa com ABERTURA-3ZK e a global fecha com FECHO-7QX', /ABERTURA-3ZK/.test(ca.text) && /FECHO-7QX/.test(ca.text), JSON.stringify(ca.text.slice(0, 160)))
const off = await call('data', 'skill.update', { id: sk.json.skill.id, name: 'Teste fecho', instructions: sk.json.skill.instructions, is_global: false }, B)
check('desativar skill global', off.status === 200 && off.json.skill.is_global === false)
const cx = await chat(B, { content: 'Diga olá em uma frase.' })
if (cx.conversation_id) created.convs.push(cx.conversation_id)
check('sem a skill global, o marcador FECHO-7QX some (comportamento muda)', cx.status === 200 && cx.text.length > 0 && !/FECHO-7QX/.test(cx.text), JSON.stringify(cx.text.slice(-100)))

section('Histórico persiste após novo login')
const s4 = await login(PASSWORD, { device_name: 'teste-4' })
const D = s4.json.access_token
const cl = await call('data', 'conv.list', {}, D)
check('conversas listadas no novo login', created.convs.every((c) => !c || cl.json.conversations.some((x) => x.id === c)))
const cmsg = await call('data', 'conv.messages', { id: c0.conversation_id }, D)
check('mensagens da conversa persistem (user+assistant, 4 no total)', cmsg.json.messages?.length === 4 && cmsg.json.messages.filter((m) => m.role === 'assistant').length === 2, String(cmsg.json.messages?.length))
const srch = await call('data', 'conv.search', { q: 'palavra FIM' }, D)
check('busca no histórico acha a conversa', srch.json.results?.some((r) => r.conversation_id === c0.conversation_id))
{ const pg = await call('data', 'prefs.get', {}, D); check('prefs.get', pg.status === 200) }

section('Segurança: conta única e isolamento')
check('account.delete não existe mais (404)', (await call('data', 'account.delete', {}, D)).status === 404)
if (ADMIN) {
  const st = await admin({ action: 'owner-status' })
  check('am-admin: um único dono com senha definida', st.status === 200 && st.json.owner_exists && st.json.password_set)
  check('am-admin sem token => 401', (await admin({ action: 'owner-status' }, 'token-errado')).status === 401)
}
check('am-admin sem cabeçalho => 401', (await call('admin', 'x', { action: 'set-password', password: 'x' })).status === 401)

section('Limpeza dos dados de teste')
for (const c of created.convs.filter(Boolean)) await call('data', 'conv.delete', { id: c }, D)
for (const m of created.mems.filter(Boolean)) await call('data', 'mem.delete', { id: m }, D)
for (const a of created.agents) await call('data', 'agent.delete', { id: a }, D)
for (const s of created.skills.filter(Boolean)) await call('data', 'skill.delete', { id: s }, D)
for (const n of created.notes) await call('data', 'note.delete', { id: n }, D)
await call('auth', 'logout-all', {}, D)
check('logout-all revoga tudo', (await call('data', 'bootstrap', {}, D)).status === 401)
summary()
void ORIGIN
